    /**
     * 给定拼音输入串（可能是不完整音节或多音节），返回候选汉字列表。
     * 最多返回 [limit] 个候选。
     */
    fun query(input: String, limit: Int = 20): List<String> {
        if (input.isEmpty()) return emptyList()
        val key = input.lowercase()
        // 1) 精确匹配
        syllables[key]?.let { return it.take(limit).map { c -> c.toString() } }
        // 2) 前缀匹配：找音节以 key 开头的
        val results = mutableListOf<String>()
        val seen = HashSet<Char>()
        for ((syl, chars) in syllables) {
            if (syl.startsWith(key)) {
                for (c in chars) {
                    if (seen.add(c)) {
                        results.add(c.toString())
                        if (results.size >= limit) return results
                    }
                }
            }
        }
        return results
    }
